module time_measure

  implicit none

  real(kind(0.d0))     :: temps_energy, temps_force, temps_descripteurs, temps_neigh, temps_stress
  PUBLIC   :: temps_energy, temps_force, temps_descripteurs, temps_neigh, temps_stress

contains

  subroutine init_time_measure()
    !initialization of time counter ...
    temps_force = 0.d0
    temps_neigh = 0.d0
    temps_energy = 0.d0
    temps_descripteurs = 0.d0
    temps_stress = 0.d0
  end subroutine

end module time_measure

